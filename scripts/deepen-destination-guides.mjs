for (const [slug, { title, html }] of Object.entries(additions)) {
  const file = path.join(process.cwd(), slug, "index.html");
  const $ = load(await fs.readFile(file, "utf8"), { decodeEntities: false });
  if (!$('#ss-related').length || !$('.ss-toc a[href="#ss-related"]').length) {
    throw new Error(`Unexpected article structure: ${slug}`);
  }
  if (!$('#ss-extra').length) {
    $('#ss-related').before(`<h2 id="ss-extra" class="wp-block-heading">${title}</h2>${html}`);
    $('.ss-toc a[href="#ss-related"]').closest('li').before(`<li><a href="#ss-extra">${title}</a></li>`);
    await fs.writeFile(file, $.html().replace(/^[ \t]+$/gm, ''));
    console.log(`Deepened ${slug}`);
  }
}
